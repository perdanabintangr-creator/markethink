export type WorkspaceUiText = typeof id;
export const workspaceUiText = (lang: Lang): WorkspaceUiText => (lang === "en" ? en : id);

/** "5 menit lalu" dsb. */
export function timeAgo(t: WorkspaceUiText, iso: string, now = Date.now()) {
  const m = Math.max(0, Math.round((now - Date.parse(iso)) / 60_000));
  if (m < 1) return t.justNow;
  if (m < 60) return t.minutesAgo(m);
  const h = Math.round(m / 60);
  if (h < 24) return t.hoursAgo(h);
  return t.daysAgo(Math.round(h / 24));
}
