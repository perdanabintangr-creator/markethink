/** Tanggal pendek ("12 Okt 2026" / "Oct 12, 2026"). "id" sama persis dengan `dateID`. */
export function dateL(iso: string | null | undefined, lang: Lang | null | undefined) {
  if (lang !== "en") return dateID(iso);
  return iso ? new Date(iso).toLocaleDateString("en-US", { day: "numeric", month: "short", year: "numeric", timeZone: "Asia/Jakarta" }) : "-";
}
